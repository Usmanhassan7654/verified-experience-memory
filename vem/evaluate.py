"""Run every memory policy over the same 60-day timeline and score each answer.

    python -m vem.evaluate          # writes results/summary.md, results/*.csv, results/daily_wrong.svg
"""
from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

from .agent import NEEDS, Agent, compute
from .memory import ABLATIONS, POLICIES, Policy
from .scenario import OUTAGE, build
from .world import SourceOfTruth

OUT = Path(__file__).resolve().parent.parent / "results"
SEEDS = [7654, 1, 2, 3, 4]


def grade(q: dict, ans, sot: SourceOfTruth) -> str:
    if ans.status == "tool_error":
        return "tool_error"
    truth = compute(q, [sot.truth(rid)[f] for rid, f in NEEDS[q["type"]](q)])
    if ans.value == truth and not ans.extras:
        return "correct"
    if "poison" in ans.labels:
        return "poisoned"
    return "stale"


def run_policy(policy: Policy, seed: int) -> dict:
    sot = SourceOfTruth()
    agent = Agent(policy, sot)
    counts = defaultdict(int)
    daily = defaultdict(lambda: defaultdict(int))
    outage = defaultdict(int)
    for ev in build(seed):
        if ev.kind == "change":
            sot.update(ev.data["rid"], **ev.data["changes"])
        elif ev.kind == "outage_start":
            sot.down = True
        elif ev.kind == "outage_end":
            sot.down = False
        elif ev.kind == "staff":
            agent.read(ev.data["text"], "staff", ev.t)
        elif ev.kind == "message":
            agent.read(ev.data["text"], "untrusted", ev.t, ev.data["label"])
        elif ev.kind == "query":
            ans = agent.answer(ev.data, ev.t)
            g = grade(ev.data, ans, sot)
            in_outage = OUTAGE[0] <= ev.t < OUTAGE[1]
            if in_outage:
                outage["queries"] += 1
                outage[g] += 1
                outage["flagged_unverified"] += int(ans.unverified)
                continue
            counts["queries"] += 1
            counts[g] += 1
            if g == "poisoned":
                counts["poisoned_instruction" if ans.followed_instruction else "poisoned_fact"] += 1
            counts["from_memory"] += int(ans.from_memory)
            daily[int(ev.t)][g] += 1
            daily[int(ev.t)]["queries"] += 1
    return {"counts": dict(counts), "outage": dict(outage), "cost": round(sot.cost, 1),
            "tool_calls": sot.calls, "rejected": agent.mem.rejected,
            "invalidations": agent.invalidations, "unneeded_invalidations": agent.unneeded_invalidations,
            "daily": {d: dict(v) for d, v in daily.items()}}


def run() -> dict:
    results = {p.name: [run_policy(p, s) for s in SEEDS] for p in POLICIES + ABLATIONS}
    OUT.mkdir(exist_ok=True)
    write_csv(results)
    write_svg(results)
    write_summary(results)
    return results


def _mean(xs):
    return sum(xs) / len(xs)


def _rate(runs, key, base="queries", where="counts"):
    return [r[where].get(key, 0) / r[where][base] for r in runs]


def fmt(xs, pct=True):
    lo, hi, m = min(xs), max(xs), _mean(xs)
    if pct:
        return f"{100 * m:.1f}%" + (f" ({100 * lo:.1f}–{100 * hi:.1f})" if hi - lo > 1e-9 else "")
    return f"{m:,.0f}" + (f" ({lo:,.0f}–{hi:,.0f})" if hi - lo > 1e-9 else "")


def write_summary(results) -> None:
    base_cost = [r["cost"] for r in results["no_memory"]]
    L = ["# Results", "", "Generated by `python -m vem.evaluate`. Do not edit by hand.",
         f"Each cell is the mean over {len(SEEDS)} query streams (seeds {SEEDS}); "
         "the range across seeds is in brackets. Changes, messages and the outage are the same "
         "in every stream.", "",
         "## Outside the outage (1,180 questions per run)", "",
         "| Policy | Correct | Stale (outdated) | Poisoned | Tool cost vs no memory | Answered from memory |",
         "|---|---|---|---|---|---|"]
    for p in POLICIES:
        runs = results[p.name]
        cost_ratio = [r["cost"] / b for r, b in zip(runs, base_cost)]
        L.append(f"| `{p.name}` | {fmt(_rate(runs, 'correct'))} | {fmt(_rate(runs, 'stale'))} | "
                 f"{fmt(_rate(runs, 'poisoned'))} | {fmt(cost_ratio)} | "
                 f"{fmt(_rate(runs, 'from_memory'))} |")
    L += ["", "### Where the poisoned answers came from", "",
          "| Policy | Followed an injected instruction | Used a poisoned fact |", "|---|---|---|"]
    for p in POLICIES:
        runs = results[p.name]
        L.append(f"| `{p.name}` | {fmt(_rate(runs, 'poisoned_instruction'))} | "
                 f"{fmt(_rate(runs, 'poisoned_fact'))} |")
    L += ["", "## Ablation: remove one safeguard from `verified`", "",
          "| Policy | Correct | Stale | Poisoned | Tool cost vs no memory |", "|---|---|---|---|---|"]
    for p in [POLICIES[-1]] + ABLATIONS:
        runs = results[p.name]
        cost_ratio = [r["cost"] / b for r, b in zip(runs, base_cost)]
        L.append(f"| `{p.name}` | {fmt(_rate(runs, 'correct'))} | {fmt(_rate(runs, 'stale'))} | "
                 f"{fmt(_rate(runs, 'poisoned'))} | {fmt(cost_ratio)} |")
    L += ["", "## What the version check costs (`verified`)", ""]
    v = results["verified"]
    inv = [r["invalidations"] for r in v]
    un = [r["unneeded_invalidations"] for r in v]
    L += [f"- Entries dropped because a source record changed: {fmt(inv, pct=False)} per run.",
          f"- Of those, fact entries whose own field had not changed (record-level versions are "
          f"coarser than the data): {fmt(un, pct=False)} per run.",
          f"- Tool cost: {fmt([r['cost'] for r in v], pct=False)} units per run, against "
          f"{fmt(base_cost, pct=False)} for `no_memory` and "
          f"{fmt([r['cost'] for r in results['trust_gated']], pct=False)} for `trust_gated`."]
    L += ["", "## During the one-day outage (source of truth unreachable)", "",
          "| Policy | Questions | Correct | Wrong | Flagged as unverified | Tool error (no answer) |",
          "|---|---|---|---|---|---|"]
    for p in POLICIES:
        r = results[p.name][0]["outage"]
        wrong = r.get("stale", 0) + r.get("poisoned", 0)
        L.append(f"| `{p.name}` | {r['queries']} | {r.get('correct', 0)} | {wrong} | "
                 f"{r.get('flagged_unverified', 0)} | {r.get('tool_error', 0)} |")
    L += ["", "(Outage table is for seed 7654.)", "",
          "## Writes the verified policy refused (seed 7654)", "",
          "| Day | Reason | Memory key | Claimed | Source said |", "|---|---|---|---|---|"]
    for rj in results["verified"][0]["rejected"]:
        L.append(f"| {rj['t']:.1f} | {rj['reason']} | {rj.get('key', '—')} | "
                 f"{rj.get('claimed', rj.get('text', ''))} | {rj.get('source', '—')} |")
    L += ["", "## Policies", ""] + [f"- `{p.name}`: {p.description}" for p in POLICIES]
    (OUT / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")


def write_csv(results) -> None:
    with (OUT / "per_run.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["policy", "seed", "queries", "correct", "stale", "poisoned",
                    "poisoned_instruction", "poisoned_fact", "tool_error",
                    "from_memory", "tool_cost", "tool_calls", "outage_queries", "outage_correct",
                    "outage_flagged_unverified", "outage_tool_error", "rejected_writes",
                    "invalidations", "unneeded_invalidations"])
        for name, runs in results.items():
            for seed, r in zip(SEEDS, runs):
                c, o = r["counts"], r["outage"]
                w.writerow([name, seed, c["queries"], c.get("correct", 0), c.get("stale", 0),
                            c.get("poisoned", 0), c.get("poisoned_instruction", 0),
                            c.get("poisoned_fact", 0), c.get("tool_error", 0), c.get("from_memory", 0),
                            r["cost"], r["tool_calls"], o.get("queries", 0), o.get("correct", 0),
                            o.get("flagged_unverified", 0), o.get("tool_error", 0),
                            len(r["rejected"]), r["invalidations"], r["unneeded_invalidations"]])
    with (OUT / "rejected_writes_verified.json").open("w", encoding="utf-8") as f:
        json.dump(results["verified"][0]["rejected"], f, indent=2)


def write_svg(results) -> None:
    """Wrong answers per day, seed 7654, as a dependency-free SVG line chart."""
    names = ["naive", "ttl_7d", "trust_gated", "version_pinned", "verified"]
    colors = {"naive": "#d1495b", "ttl_7d": "#edae49", "trust_gated": "#8d6cab",
              "version_pinned": "#00798c", "verified": "#2e7d32"}
    W, H, pad = 760, 300, 44
    days = range(60)
    series = {n: [results[n][0]["daily"].get(d, {}).get("stale", 0) +
                  results[n][0]["daily"].get(d, {}).get("poisoned", 0) for d in days] for n in names}
    ymax = max(max(v) for v in series.values()) or 1
    x = lambda d: pad + d * (W - 2 * pad) / 59
    y = lambda v: H - pad - v * (H - 2 * pad) / ymax
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H + 40}" '
             f'font-family="Segoe UI, Helvetica, Arial, sans-serif" font-size="11">',
             f'<rect width="{W}" height="{H + 40}" fill="white"/>',
             f'<text x="{pad}" y="18" font-size="13" font-weight="600">Wrong answers per day '
             f'(stale + poisoned), seed 7654</text>']
    for v in range(0, ymax + 1, max(1, ymax // 5)):
        parts.append(f'<line x1="{pad}" x2="{W - pad}" y1="{y(v)}" y2="{y(v)}" stroke="#e5e5e5"/>'
                     f'<text x="{pad - 6}" y="{y(v) + 4}" text-anchor="end" fill="#555">{v}</text>')
    for d in range(0, 60, 10):
        parts.append(f'<text x="{x(d)}" y="{H - pad + 16}" text-anchor="middle" fill="#555">day {d}</text>')
    parts.append(f'<rect x="{x(OUTAGE[0])}" y="{pad}" width="{x(OUTAGE[1]) - x(OUTAGE[0])}" '
                 f'height="{H - 2 * pad}" fill="#999" opacity="0.15"/>'
                 f'<text x="{x(OUTAGE[0]) + 3}" y="{pad + 12}" fill="#666">outage</text>')
    for i, n in enumerate(names):
        # Outage-day questions are scored separately, so the line breaks there.
        for seg in (range(0, int(OUTAGE[0])), range(int(OUTAGE[1]), 60)):
            pts = " ".join(f"{x(d):.1f},{y(series[n][d]):.1f}" for d in seg)
            parts.append(f'<polyline fill="none" stroke="{colors[n]}" stroke-width="2" points="{pts}"/>')
        lx = pad + i * 140
        parts.append(f'<line x1="{lx}" x2="{lx + 18}" y1="{H + 20}" y2="{H + 20}" stroke="{colors[n]}" '
                     f'stroke-width="3"/><text x="{lx + 24}" y="{H + 24}">{n}</text>')
    parts.append("</svg>")
    (OUT / "daily_wrong.svg").write_text("\n".join(parts), encoding="utf-8")


if __name__ == "__main__":
    run()
    print((OUT / "summary.md").read_text(encoding="utf-8"))
